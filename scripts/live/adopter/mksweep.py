"""Compile every Rust block of the README and the book as an adopter would.

    mksweep.py NAME default|all

Makes `$ADOPTER_SCRATCH/adopter-projects/NAME`: a library crate, outside the
repository, whose doc comments are the pages (each ```rust block is a doctest,
exactly as `book-tests/` does), depending on the unpacked tarballs of
01-package.sh through `[patch.crates-io]`.

`default` asks for each crate by version with its default features, which is
what `a2a-protocol-sdk = "0.16"` and `a2a-protocol-server = "0.16"` give. A
block that needs a feature then fails here unless the page told its reader to
enable it; `book-tests/` cannot see that, because it turns every feature on.
`all` turns every feature of the four crates on, to separate "needs a
feature" from "does not compile".
"""
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(Path(__file__).parent))
import book_blocks  # noqa: E402

ALL = {
    "a2a-protocol-types": ["signing", "audit", "proto"],
    "a2a-protocol-client": ["signing", "websocket", "grpc", "grpc-tls", "testing"],
    "a2a-protocol-server": [
        "signing", "sqlite", "postgres", "websocket", "grpc", "grpc-tls", "otlp",
        "otlp-json", "otel-prometheus", "conformance", "axum", "tool-loop",
        "auth-jwt", "encryption", "audit",
    ],
    "a2a-protocol-sdk": [
        "signing", "grpc", "grpc-tls", "websocket", "sqlite", "postgres", "otlp-json",
        "otel-prometheus", "axum", "tool-loop", "auth-jwt", "encryption", "audit",
    ],
}


def main():
    name, mode = sys.argv[1], sys.argv[2]
    scratch = Path(os.environ["ADOPTER_SCRATCH"])
    proj = scratch / "adopter-projects" / name
    for child in list(proj.iterdir()) if proj.exists() else []:
        if child.name != "target":
            shutil.rmtree(child) if child.is_dir() else child.unlink()
    (proj / "src").mkdir(parents=True, exist_ok=True)
    (proj / "pages").mkdir(exist_ok=True)

    lib = [
        "// Generated by mksweep.py: every page is a doc comment.",
        "#![allow(rustdoc::broken_intra_doc_links, rustdoc::bare_urls, rustdoc::invalid_html_tags, rustdoc::invalid_rust_codeblocks)]",
    ]
    for p in book_blocks.pages():
        rel = p.relative_to(ROOT)
        dst = proj / "pages" / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(p, dst)
        mod = "page_" + re.sub(r"[^a-z0-9]+", "_", str(rel.with_suffix("")).lower()).strip("_")
        lib.append(f'#[doc = include_str!("../pages/{rel}")]\npub mod {mod} {{}}')
    (proj / "src" / "lib.rs").write_text("\n".join(lib) + "\n")

    deps = ["[dependencies]"]
    for crate, feats in ALL.items():
        if mode == "all":
            deps.append(f'{crate} = {{ version = "0.16", features = {feats!r} }}'.replace("'", '"'))
        else:
            deps.append(f'{crate} = "0.16"')
    deps += [
        # Crates the pages' blocks name besides the SDK (a reader adds these
        # when a page says so; their feature lists follow `book-tests/`).
        'tokio = { version = "1", features = ["full"] }',
        'serde = { version = "1", features = ["derive"] }',
        'serde_json = "1"',
        'uuid = { version = "1", features = ["v4"] }',
        'tracing-subscriber = { version = "0.3", features = ["env-filter"] }',
        'hyper = { version = "1", features = ["full"] }',
        'hyper-util = { version = "0.1", features = ["full"] }',
        'http-body-util = "0.1"',
        'futures-util = "0.3"',
        'axum = "0.8"',
        'tonic = "0.14"',
        'sqlx = { version = "0.9", features = ["postgres", "runtime-tokio"] }',
    ]
    patch = ["[patch.crates-io]"]
    for d in sorted((scratch / "unpacked").iterdir()):
        patch.append(f'{re.sub(r"-[0-9]+[.][0-9]+[.][0-9]+$", "", d.name)} = {{ path = "{d}" }}')
    (proj / "Cargo.toml").write_text(
        f'[package]\nname = "{name.replace("-", "_")}"\nversion = "0.1.0"\nedition = "2024"\n\n[lib]\ndoctest = true\n\n'
        + "\n".join(deps) + "\n\n" + "\n".join(patch) + "\n"
    )
    print(proj)


if __name__ == "__main__":
    main()
