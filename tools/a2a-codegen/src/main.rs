//! Generates `a2a-protocol-types`' public types from `a2a.proto` (ADR 0016).
//!
//! ```text
//! a2a-codegen write    # regenerate crates/a2a-protocol-types/src/generated/
//! a2a-codegen --check  # fail when the checked-in output is not what write makes
//! a2a-codegen dump     # the proto as the generator reads it
//! ```

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use sha2::{Digest, Sha256};

mod config;
mod emit;
mod oneof;
mod proto;
mod text;

/// The repository root: this crate is `tools/a2a-codegen`.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("tools/a2a-codegen sits two levels below the repository root")
        .to_path_buf()
}

fn proto_dir() -> PathBuf {
    repo_root().join("proto/a2a_v1")
}

fn generated_dir() -> PathBuf {
    repo_root().join("crates/a2a-protocol-types/src/generated")
}

fn load() -> Result<proto::Schema, String> {
    let dir = proto_dir();
    proto::load(&dir.join("a2a.proto"), &[&dir])
}

/// What `write` produces, as (relative path, contents).
fn generate() -> Result<BTreeMap<String, String>, String> {
    let schema = load()?;
    let config_path = repo_root().join("crates/a2a-protocol-types/codegen.toml");
    let text = std::fs::read_to_string(&config_path)
        .map_err(|e| format!("{}: {e}", config_path.display()))?;
    let config = config::Config::parse(&text)?;
    config.validate(&schema)?;
    let proto = std::fs::read(proto_dir().join("a2a.proto")).map_err(|e| e.to_string())?;
    let sha: String = Sha256::digest(&proto)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    emit::emit(&schema, &config, &sha)
}

/// The `.rs` files now in `src/generated/`.
fn on_disk() -> Result<BTreeMap<String, String>, String> {
    let mut files = BTreeMap::new();
    let Ok(entries) = std::fs::read_dir(generated_dir()) else {
        return Ok(files);
    };
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().is_some_and(|x| x == "rs") {
            let name = path
                .file_name()
                .expect("a file")
                .to_string_lossy()
                .into_owned();
            let text = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;
            files.insert(name, text);
        }
    }
    Ok(files)
}

fn write() -> Result<(), String> {
    let wanted = generate()?;
    let dir = generated_dir();
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    for stale in on_disk()?.keys().filter(|k| !wanted.contains_key(*k)) {
        std::fs::remove_file(dir.join(stale)).map_err(|e| e.to_string())?;
    }
    for (name, text) in &wanted {
        std::fs::write(dir.join(name), text).map_err(|e| e.to_string())?;
    }
    println!(
        "a2a-codegen: wrote {} files to {}",
        wanted.len(),
        dir.display()
    );
    Ok(())
}

fn check() -> Result<(), String> {
    let wanted = generate()?;
    let have = on_disk()?;
    let mut problems = Vec::new();
    for (name, text) in &wanted {
        match have.get(name) {
            None => problems.push(format!("{name} is missing")),
            Some(found) if found != text => {
                let line = found
                    .lines()
                    .zip(text.lines())
                    .position(|(a, b)| a != b)
                    .unwrap_or_else(|| found.lines().count().min(text.lines().count()))
                    + 1;
                problems.push(format!(
                    "{name} differs from what the proto generates, from line {line}"
                ));
            }
            Some(_) => {}
        }
    }
    for name in have.keys().filter(|k| !wanted.contains_key(*k)) {
        problems.push(format!("{name} is not generated by anything"));
    }
    if problems.is_empty() {
        println!(
            "a2a-codegen: {} generated files match the proto",
            wanted.len()
        );
        Ok(())
    } else {
        Err(format!(
            "crates/a2a-protocol-types/src/generated/ is out of date:\n  {}\n\
             run `cargo run --manifest-path tools/a2a-codegen/Cargo.toml -- write` and commit the result",
            problems.join("\n  ")
        ))
    }
}

fn main() -> ExitCode {
    let mode = std::env::args().nth(1).unwrap_or_default();
    let result = match mode.as_str() {
        "write" => write(),
        "--check" | "check" => check(),
        "dump" => load().map(|schema| dump(&schema)),
        _ => Err(format!(
            "usage: a2a-codegen write | --check | dump (got {mode:?})"
        )),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(why) => {
            eprintln!("a2a-codegen: {why}");
            ExitCode::FAILURE
        }
    }
}

fn dump(schema: &proto::Schema) {
    for m in &schema.messages {
        println!("message {}", m.name);
        for f in &m.fields {
            println!(
                "  {:>2} {:<28} json={:<28} {:?}{}{}{}{}{}",
                f.number,
                f.name,
                f.json_name,
                f.ty,
                if f.repeated { " repeated" } else { "" },
                f.map_key
                    .as_ref()
                    .map(|k| format!(" map<{k:?}>"))
                    .unwrap_or_default(),
                if f.required { " REQUIRED" } else { "" },
                if f.optional { " optional" } else { "" },
                f.oneof
                    .as_ref()
                    .map(|o| format!(" oneof={o}"))
                    .unwrap_or_default(),
            );
        }
    }
    for e in &schema.enums {
        println!("enum {}", e.name);
        for v in &e.values {
            println!("  {:>2} {}", v.number, v.name);
        }
    }
}
