//! Rust source for the configured types (ADR 0016).
//!
//! The output is a pure function of the proto, its SHA-256 and the
//! configuration: no timestamps, no map iteration order (every map is a
//! `BTreeMap`, every list follows the proto), so `--check` can compare bytes.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::config::{Config, FieldConfig};
use crate::proto::{Enum, Field, FieldType, Message, PACKAGE, Schema};
use crate::text::{camel, doc, pascal, screaming};

/// The generated files, by path relative to `src/generated/`.
pub fn emit(
    schema: &Schema,
    config: &Config,
    proto_sha256: &str,
) -> Result<BTreeMap<String, String>, String> {
    let mut modules: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for e in &schema.enums {
        if let Some(ec) = config.enums.get(&e.name) {
            let (module, _) = split_path(config, &e.name)?;
            modules
                .entry(module)
                .or_default()
                .push(emit_enum(e, ec, config)?);
        }
    }
    for m in &schema.messages {
        if let Some(mc) = config.messages.get(&m.name) {
            let (module, _) = split_path(config, &m.name)?;
            modules
                .entry(module)
                .or_default()
                .push(emit_message(m, mc, config)?);
        }
    }

    let mut files = BTreeMap::new();
    let licence = "// SPDX-License-Identifier: Apache-2.0\n\
                   // Copyright 2026 Tom F. <tomf@tomtomtech.net> (https://github.com/tomtom215)\n";
    for (module, items) in &modules {
        // Included, not a module of its own: each type is defined in the
        // module that documents it, beside its impl blocks and the types it
        // refers to. Defined in a separate module, `Message`'s serialization
        // ran up to 89% slower in release builds with 16 codegen units and
        // no LTO (protocol/payload_scaling, ADR 0016).
        let header = format!(
            "// @generated by tools/a2a-codegen from proto/a2a_v1/a2a.proto,\n\
             // sha256 {proto_sha256}.\n\
             // Included by the `{}` module. Do not edit: change the proto or\n\
             // crates/a2a-protocol-types/codegen.toml and regenerate (ADR 0016).\n",
            module
        );
        let file = format!("{licence}{header}\n{}", items.join("\n"));
        files.insert(format!("{}.rs", module.replace("::", "_")), rustfmt(&file)?);
    }
    Ok(files)
}

/// A derive as written in the generated file: serde's by path, since the
/// including module may import serde's names or not.
fn derive_path(derive: &str) -> String {
    match derive {
        "Serialize" | "Deserialize" => format!("serde::{derive}"),
        other => other.to_owned(),
    }
}

pub(crate) fn derives(list: &[String]) -> String {
    list.iter()
        .map(|d| derive_path(d))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `task::Task` as (`task`, `Task`). A nested path's file joins its
/// modules with `_`.
pub(crate) fn split_path(config: &Config, proto_name: &str) -> Result<(String, String), String> {
    let path = config
        .paths
        .get(proto_name)
        .ok_or_else(|| format!("[paths] has no entry for {proto_name}"))?;
    let (module, name) = path
        .rsplit_once("::")
        .ok_or_else(|| format!("[paths] {proto_name} = {path:?} names no module"))?;
    Ok((module.to_owned(), name.to_owned()))
}

pub(crate) fn rust_name(config: &Config, proto_name: &str) -> Result<String, String> {
    split_path(config, proto_name).map(|(_, name)| name)
}

fn emit_enum(e: &Enum, ec: &crate::config::EnumConfig, config: &Config) -> Result<String, String> {
    let name = rust_name(config, &e.name)?;
    let mut out = doc(
        &e.name,
        &e.comment,
        ec.doc.as_deref(),
        ec.doc_append.as_deref(),
        0,
    )?;
    let _ = writeln!(out, "#[derive({})]", derives(&ec.derives));
    for attr in &ec.attrs {
        let _ = writeln!(out, "{attr}");
    }
    let _ = writeln!(out, "pub enum {name} {{");
    let prefix = format!("{}_", screaming(&e.name));
    for v in &e.values {
        let vc = ec.values.get(&v.name);
        let variant = pascal(
            v.name
                .strip_prefix(&prefix)
                .ok_or_else(|| format!("{}.{} does not start with {prefix}", e.name, v.name))?,
        );
        out.push_str(&doc(
            &format!("{}.{}", e.name, v.name),
            &v.comment,
            vc.and_then(|c| c.doc.as_deref()),
            vc.and_then(|c| c.doc_append.as_deref()),
            1,
        )?);
        let mut serde = vec![format!("rename = {:?}", v.name)];
        for alias in vc.map(|c| c.aliases.as_slice()).unwrap_or_default() {
            serde.push(format!("alias = {alias:?}"));
        }
        let _ = writeln!(out, "    #[serde({})]", serde.join(", "));
        // The discriminant is the proto number, so `as i32` agrees with the
        // prost enum whatever order the proto declares its values in.
        let _ = writeln!(out, "    {variant} = {},", v.number);
    }
    out.push_str("}\n");
    Ok(out)
}

fn emit_message(
    m: &Message,
    mc: &crate::config::MessageConfig,
    config: &Config,
) -> Result<String, String> {
    if !m.oneofs.is_empty() {
        return crate::oneof::emit(m, mc, config);
    }
    let name = rust_name(config, &m.name)?;
    let mut out = doc(
        &m.name,
        &m.comment,
        mc.doc.as_deref(),
        mc.doc_append.as_deref(),
        0,
    )?;
    let _ = writeln!(out, "#[derive({})]", derives(&mc.derives));
    out.push_str("#[serde(rename_all = \"camelCase\")]\n");
    for attr in &mc.attrs {
        let _ = writeln!(out, "{attr}");
    }
    let _ = writeln!(out, "pub struct {name} {{");
    let default = FieldConfig::default();
    for f in &m.fields {
        let fc = mc.fields.get(&f.name).unwrap_or(&default);
        let field_name = fc.rename.clone().unwrap_or_else(|| f.name.clone());
        let ty = match &fc.ty {
            Some(ty) => ty.clone(),
            None => {
                default_type(f, config).map_err(|why| format!("{}.{}: {why}", m.name, f.name))?
            }
        };
        out.push_str(&doc(
            &format!("{}.{}", m.name, f.name),
            &f.comment,
            fc.doc.as_deref(),
            fc.doc_append.as_deref(),
            1,
        )?);
        let mut serde = Vec::new();
        if camel(&field_name) != f.json_name {
            serde.push(format!("rename = {:?}", f.json_name));
        }
        for alias in &fc.aliases {
            serde.push(format!("alias = {alias:?}"));
        }
        field(&mut out, &field_name, &ty, serde, &fc.serde);
    }
    for extra in &mc.extra {
        out.push_str(&doc(
            &format!("{}.{}", m.name, extra.name),
            "",
            Some(&extra.doc),
            None,
            1,
        )?);
        field(&mut out, &extra.name, &extra.ty, Vec::new(), &extra.serde);
    }
    out.push_str("}\n");
    Ok(out)
}

/// One field: its `#[serde(...)]` (the generated arguments, then the
/// configured ones) and its declaration. An `Option` is skipped when absent
/// unless the configuration says how it is skipped.
pub(crate) fn field(
    out: &mut String,
    name: &str,
    ty: &str,
    mut serde: Vec<String>,
    configured: &[String],
) {
    let explicit_skip = configured.iter().any(|s| s.starts_with("skip_serializing"));
    if ty.starts_with("Option<") && !explicit_skip {
        serde.push("skip_serializing_if = \"Option::is_none\"".to_owned());
    }
    serde.extend(configured.iter().cloned());
    if !serde.is_empty() {
        let _ = writeln!(out, "    #[serde({})]", serde.join(", "));
    }
    let _ = writeln!(out, "    pub {name}: {ty},");
}

/// The default translation of a field's type (ADR 0016's table).
pub(crate) fn default_type(f: &Field, config: &Config) -> Result<String, String> {
    if f.map_key.is_some() {
        return Err("a map field needs an explicit `type`".to_owned());
    }
    let base = match &f.ty {
        FieldType::String => "String".to_owned(),
        FieldType::Bool => "bool".to_owned(),
        FieldType::I32 => "i32".to_owned(),
        FieldType::I64 => "i64".to_owned(),
        FieldType::U32 => "u32".to_owned(),
        FieldType::U64 => "u64".to_owned(),
        FieldType::F32 => "f32".to_owned(),
        FieldType::F64 => "f64".to_owned(),
        FieldType::Bytes => return Err("a bytes field needs an explicit `type`".to_owned()),
        FieldType::Message(full) => match full.as_str() {
            "google.protobuf.Struct" | "google.protobuf.Value" => "serde_json::Value".to_owned(),
            "google.protobuf.Timestamp" => "String".to_owned(),
            other => crate_path(other, config)?,
        },
        FieldType::Enum(full) => crate_path(full, config)?,
    };
    let ty = if f.repeated {
        format!("Vec<{base}>")
    } else {
        base
    };
    Ok(if f.required {
        ty
    } else {
        format!("Option<{ty}>")
    })
}

fn crate_path(full_name: &str, config: &Config) -> Result<String, String> {
    let name = full_name
        .strip_prefix(PACKAGE)
        .and_then(|s| s.strip_prefix('.'))
        .ok_or_else(|| format!("{full_name} is outside {PACKAGE}; give the field a `type`"))?;
    let path = config
        .paths
        .get(name)
        .ok_or_else(|| format!("[paths] has no entry for {name}"))?;
    Ok(format!("crate::{path}"))
}

/// Formats `source` with the toolchain's `rustfmt`, as `cargo fmt` would.
fn rustfmt(source: &str) -> Result<String, String> {
    use std::io::Write as _;
    use std::process::{Command, Stdio};
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("cannot run rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .expect("stdin is piped")
        .write_all(source.as_bytes())
        .map_err(|e| format!("rustfmt stdin: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "rustfmt refused the generated source:\n{}\n--- source ---\n{source}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    String::from_utf8(out.stdout).map_err(|e| format!("rustfmt output: {e}"))
}
