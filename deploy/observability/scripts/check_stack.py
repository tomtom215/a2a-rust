"""Static checks on deploy/observability that promtool cannot make, and the
Kubernetes manifests generated from it.

1. The caller-class pattern in prometheus/rules/a2a-recording.yml (statuses the
   rules do not count as failures, audit NEW-c-1) is the same in all three rules
   that carry it, and is exactly the set the code defines: every JSON-RPC code
   whose ErrorCode::http_status is a 4xx (crates/a2a-protocol-types/src/error.rs),
   any 4xx, and every gRPC status other than OK and the six server-side failures
   of grpc_server_error (crates/a2a-protocol-server/src/rpc_span/names.rs,
   dispatch/grpc/helpers.rs). A code added to A2A fails this until the rules
   say which side it is on.
2. prometheus/prometheus-compose.yml has prometheus.yml's `global`, `otlp`,
   `storage` and `rule_files` blocks unchanged.
3. Every image in docker-compose.yml is pinned by digest (audit C-19), and
   the Prometheus and Alertmanager tags are the versions install_tools.sh
   installs promtool and amtool from, so CI checks with the tools the stack
   runs (a Dependabot image bump fails until the tool pins move too).
4. deploy/kubernetes/observability/ holds exactly what --write-kubernetes
   generates from the rules and dashboards (audit C-22): a PrometheusRule and
   one dashboard ConfigMap per dashboard.

Usage: check_stack.py                     # exit 0 when all hold, 1 otherwise
       check_stack.py --skip-kubernetes   # checks 1-3 only (while editing the rules)
       check_stack.py --write-kubernetes  # regenerate deploy/kubernetes/observability
"""
from __future__ import annotations

import json
import re
import signal
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
OBS = ROOT / "deploy/observability"
K8S = ROOT / "deploy/kubernetes/observability"
RULES = OBS / "prometheus/rules"
HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Copyright 2026 Tom F. <tomf@tomtomtech.net> (https://github.com/tomtom215)\n"
    "#\n"
    "# GENERATED by deploy/observability/scripts/check_stack.py --write-kubernetes.\n"
    "# Do not edit: change the sources and regenerate (CI fails when this file\n"
    "# and its sources disagree). Sources:\n"
    "{source}"
)


# One match arm of ErrorCode::http_status: `Self::A | Self::B => 404`, with the
# alternatives on one line or on several. The `|` between two names is required,
# so no run of whitespace can be matched two ways: the earlier form,
# `((?:\|?\s*Self::\w+\s*)+)=>`, let the trailing `\s*` of one name and the
# leading `\|?\s*` of the next both take the same spaces, and took time doubling
# with every name when the arm had no `=>` (CodeQL py/redos).
_ARM = re.compile(r"((?:\|\s*)?Self::\w+(?:\s*\|\s*Self::\w+)*)\s*=>\s*(\d{3})")


def _self_test() -> list[str]:
    """Proves _ARM reads the arms it is for and cannot be made to backtrack."""
    problems: list[str] = []
    sample = (
        "Self::A | Self::B => 404,\n"
        "            Self::C\n"
        "            | Self::D => 500,\n"
        "            Self::E => 400,\n"
    )
    got = [(re.findall(r"Self::(\w+)", names), status) for names, status in _ARM.findall(sample)]
    want = [(["A", "B"], "404"), (["C", "D"], "500"), (["E"], "400")]
    if got != want:
        problems.append(f"self-test: the arm pattern read {got}, expected {want}")

    def too_slow(_signum, _frame):
        raise TimeoutError

    # 60 names and no `=>`: instant for an unambiguous pattern, longer than the
    # age of the universe for the one this replaced. The alarm turns a
    # reintroduced ambiguity into a failure instead of a hung job.
    pathological = "Self::0" + " Self::0" * 60
    if hasattr(signal, "SIGALRM"):
        signal.signal(signal.SIGALRM, too_slow)
        signal.alarm(5)
    try:
        if _ARM.findall(pathological):
            problems.append("self-test: the arm pattern matched a line with no `=>`")
    except TimeoutError:
        problems.append("self-test: the arm pattern took over 5 s on a line of 61 names (backtracking)")
    finally:
        if hasattr(signal, "SIGALRM"):
            signal.alarm(0)
    return problems


def jsonrpc_caller_codes() -> set[str]:
    """JSON-RPC codes whose A2A §5.4 HTTP status is a 4xx, read from the types crate."""
    text = (ROOT / "crates/a2a-protocol-types/src/error.rs").read_text(encoding="utf-8")
    codes = dict(re.findall(r"^\s+(\w+) = (-32\d{3}),$", text, re.M))
    body = text[text.index("pub const fn http_status(self) -> u16 {"):]
    body = body[: body.index("\n    }\n")]
    caller: set[str] = set()
    seen: set[str] = set()
    for names, status in _ARM.findall(body):
        for name in re.findall(r"Self::(\w+)", names):
            seen.add(name)
            if status.startswith("4"):
                caller.add(codes[name])
    if seen != set(codes):
        raise SystemExit(f"check_stack: http_status does not cover {sorted(set(codes) - seen)}")
    return caller


def grpc_caller_codes() -> set[str]:
    """gRPC status names other than OK and the server-side failures."""
    helpers = (ROOT / "crates/a2a-protocol-server/src/dispatch/grpc/helpers.rs").read_text(encoding="utf-8")
    names = set(re.findall(r'Code::\w+ => "([A-Z_]+)"', helpers))
    rule = (ROOT / "crates/a2a-protocol-server/src/rpc_span/names.rs").read_text(encoding="utf-8")
    body = rule[rule.index("pub fn grpc_server_error"):]
    server = set(re.findall(r'"([A-Z_]+)"', body[: body.index("\n}\n")]))
    if len(names) != 17 or len(server) != 6:
        raise SystemExit(f"check_stack: read {len(names)} gRPC codes and {len(server)} server failures; expected 17 and 6")
    return names - server - {"OK"}


def check_caller_pattern(problems: list[str]) -> None:
    expected = jsonrpc_caller_codes() | grpc_caller_codes() | {"4[0-9][0-9]"}
    doc = yaml.safe_load((RULES / "a2a-recording.yml").read_text(encoding="utf-8"))
    exprs = {r["record"]: r["expr"] for g in doc["groups"] for r in g["rules"] if "record" in r}
    uses = {
        "a2a:rpc_server_errors:rate5m": r'error_type!~"cancelled\|([^"]*)"',
        "a2a:rpc_server_caller_errors:rate5m": r'rpc_status_code=~"([^"]*)"',
        "a2a:rpc_client_error_ratio:rate5m": r'error_type!~"cancelled\|([^"]*)"',
    }
    found = {}
    for record, pattern in uses.items():
        m = re.search(pattern, exprs.get(record, ""))
        if not m:
            problems.append(f"a2a-recording.yml: {record} carries no caller-class pattern")
            continue
        found[record] = m.group(1)
        got = set(m.group(1).split("|"))
        if got != expected:
            problems.append(
                f"a2a-recording.yml: {record}: caller-class pattern differs from the code: "
                f"missing {sorted(expected - got)}, extra {sorted(got - expected)}")
    if len(set(found.values())) > 1:
        problems.append("a2a-recording.yml: the caller-class pattern is not written the same in all three rules")


def check_compose_prometheus(problems: list[str]) -> None:
    base = yaml.safe_load((OBS / "prometheus/prometheus.yml").read_text(encoding="utf-8"))
    compose = yaml.safe_load((OBS / "prometheus/prometheus-compose.yml").read_text(encoding="utf-8"))
    for key in ("global", "otlp", "storage", "rule_files"):
        if base.get(key) != compose.get(key):
            problems.append(f"prometheus-compose.yml: `{key}` differs from prometheus.yml")


def check_image_pins(problems: list[str]) -> None:
    doc = yaml.safe_load((OBS / "docker-compose.yml").read_text(encoding="utf-8"))
    tools = (OBS / "scripts/install_tools.sh").read_text(encoding="utf-8")
    pins = dict(re.findall(r"^(PROMETHEUS|ALERTMANAGER)_VERSION=(\S+)$", tools, re.M))
    for name, svc in doc["services"].items():
        image = svc.get("image", "")
        if not re.fullmatch(r"[\w./-]+:[\w.-]+@sha256:[0-9a-f]{64}", image):
            problems.append(f"docker-compose.yml: service {name}: image {image!r} is not pinned by tag and digest")
        for repo, key in (("prom/prometheus", "PROMETHEUS"), ("prom/alertmanager", "ALERTMANAGER")):
            if image.startswith(repo + ":") and not image.startswith(f"{repo}:v{pins.get(key)}@"):
                problems.append(
                    f"docker-compose.yml: service {name} runs {image.split('@')[0]}, but install_tools.sh "
                    f"installs {key.lower()} {pins.get(key)}; move the pin and its SHA-256 together")


class _Block(str):
    """A string dumped as a YAML literal block."""


def _block(dumper: yaml.SafeDumper, value: _Block) -> yaml.Node:
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")


def _blocks(node):
    if isinstance(node, dict):
        return {k: _blocks(v) for k, v in node.items()}
    if isinstance(node, list):
        return [_blocks(v) for v in node]
    if isinstance(node, str) and "\n" in node:
        return _Block(node if node.endswith("\n") else node + "\n")
    return node


def _dump(doc) -> str:
    dumper = yaml.SafeDumper
    dumper.add_representer(_Block, _block)
    return yaml.dump(_blocks(doc), Dumper=dumper, sort_keys=False, width=4096, allow_unicode=True)


def kubernetes_files() -> dict[str, str]:
    """The generated manifests, by file name."""
    rule_files = sorted(RULES.glob("*.yml"))
    groups = []
    for path in rule_files:
        groups.extend(yaml.safe_load(path.read_text(encoding="utf-8"))["groups"])
    rule = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "a2a-rust", "labels": {"app.kubernetes.io/part-of": "a2a-rust"}},
        "spec": {"groups": groups},
    }
    sources = "".join(f"#   {p.relative_to(ROOT)}\n" for p in rule_files)
    out = {"prometheusrule.yaml": HEADER.format(source=sources) + "---\n" + _dump(rule)}
    boards = sorted((OBS / "grafana/dashboards").glob("*.json"))
    docs = []
    for path in boards:
        docs.append(_dump({
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": {
                "name": f"grafana-dashboard-{path.stem}",
                # The Grafana sidecar of kube-prometheus-stack (and the Grafana
                # Helm chart) loads ConfigMaps with this label, into the folder
                # this annotation names (sidecar.dashboards.folderAnnotation).
                "labels": {"grafana_dashboard": "1", "app.kubernetes.io/part-of": "a2a-rust"},
                "annotations": {"grafana_folder": "A2A"},
            },
            "data": {path.name: _Block(json.dumps(json.loads(path.read_text(encoding="utf-8")), indent=2) + "\n")},
        }))
    sources = "".join(f"#   {p.relative_to(ROOT)}\n" for p in boards)
    out["grafana-dashboards.yaml"] = HEADER.format(source=sources) + "".join("---\n" + d for d in docs)
    return out


def check_kubernetes(problems: list[str]) -> None:
    for name, text in kubernetes_files().items():
        path = K8S / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            problems.append(f"{path.relative_to(ROOT)}: differs from its sources; run {Path(__file__).relative_to(ROOT)} --write-kubernetes")


def main(argv: list[str]) -> int:
    if argv == ["--write-kubernetes"]:
        K8S.mkdir(parents=True, exist_ok=True)
        for name, text in kubernetes_files().items():
            (K8S / name).write_text(text, encoding="utf-8")
            print(f"wrote {(K8S / name).relative_to(ROOT)}")
        return 0
    if argv not in ([], ["--skip-kubernetes"]):
        print(__doc__, file=sys.stderr)
        return 2
    problems: list[str] = _self_test()
    check_caller_pattern(problems)
    check_compose_prometheus(problems)
    check_image_pins(problems)
    if not argv:
        check_kubernetes(problems)
    for p in problems:
        print(f"check_stack: {p}")
    print("check_stack:", "FAILED" if problems else "ok")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
